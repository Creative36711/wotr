#!/usr/bin/env python3
"""
Конфигурация модуля определения исхода матча BFME2:RotWK.

Здесь собраны ВСЕ константы (координаты, пороги, задержки, шаблоны, цвета
линий), чтобы калибровка на реальных скриншотах не требовала правки
алгоритма.

Базовое разрешение — 1920x1080 (скриншоты в _tools/screenshots). Все зоны
заданы ДОЛЯМИ экрана (fractions), а не пикселями: на другом разрешении зона
масштабируется автоматически. Шаблоны (иконки) вырезаны в исходниках под
1080p, поэтому при анализе масштабируются коэффициентом h/1080.

ТАСКА (кратко):
  * после боя игра показывает экран статистики «Счёт»;
  * на графике-таймлайне у ПОБЕДИТЕЛЕЙ в конце полосы — зелёная «монета»
    (victory_coin.png), у ПРОИГРАВШИХ — красная «вспышка» (defeat_flame.png);
  * НАША задача — определить КОМАНДУ-ПОБЕДИТЕЛЯ (добро/зло). Игроков по
    отдельности не отслеживаем, но цвет каждой полосы соответствует цвету
    фракции (задан заранее при старте игры);
  * если никто не победил (иконок победы нет) — это сдача/выход; команда
    сдавшегося проигрывает.

Все пороги можно переопределить при создании детектора:

    detector = MatchResultDetector(players, config={
        "icon_threshold": 0.75,
        ...
    })

или через config.json -> "match_detector" (запуск из main.py).
"""

from dataclasses import dataclass, field, fields, replace
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

# ---------------------------------------------------------------------------
# Базовые параметры экрана и шаблонов
# ---------------------------------------------------------------------------

# Разрешение, в котором вырезаны шаблоны и измерены зоны UI.
REFERENCE_RESOLUTION = (1920, 1080)

# Папка с шаблонами (PNG, 24bit RGB, тёмный фон врезан в сами изображения).
TEMPLATES_DIR = Path(__file__).resolve().parent / "assets" / "templates"

# Имена файлов шаблонов. Ключи — смысловые роли шаблонов.
TEMPLATE_FILES = {
    # Детекторы экрана статистики (должны быть видны одновременно).
    "fortress": "fortress_icon.png",             # иконка «Крепость» в легенде внизу
    "score_marker": "score_screen_marker.png",   # декоративный элемент шапки «Счёт»
    # Иконки исходов на графике-таймлайне.
    "victory": "victory_coin.png",               # золотая монета — победа игрока
    "defeat": "defeat_flame.png",                # красная вспышка — поражение игрока
}

# ---------------------------------------------------------------------------
# Координаты (проверены по скриншотам 1920x1080)
# ---------------------------------------------------------------------------

# Кнопка «Пропустить» (слева от вкладок? нет — внизу справа, скип анимации
# вкладок). Проверяется по скриншотам: центр ~ (1730, 925) / 1080p.
# Дробные координаты (доли окна).
SKIP_BUTTON_FRAC = (0.9109, 0.9583)

# Вкладка «Счёт» (доли экрана x0, y0, x1, y1). Замерено на скриншотах:
# вкладка x≈845..1010, y≈150..195.
SCORE_TAB_ROI = (845 / 1920, 150 / 1080, 1010 / 1920, 195 / 1080)

# Область графика-таймлайна, где рисуются линии игроков и их иконки.
#  * x0 = 190 — левее оси Y;
#  * y0 = 240 — под заголовком «ВРЕМЕННАЯ ШКАЛА»;
#  * x1 = 1310 — СПРАВА от монеты/пламени (панель «Рейтинг» x>=1330 исключена);
#  * y1 = 815 — НАД легендой («Крепость»/«Победа»/«Поражение» y≈840..905),
#    чтобы иконки ЛЕГЕНДЫ не попадали в поиск (они совпадают с шаблонами
#    идеально, но это UI, а не результат матча).
CHART_ROI = (190 / 1920, 240 / 1080, 1310 / 1920, 815 / 1080)

# Запасная область поиска иконок, если chart_roi пуст.
ICON_FALLBACK_ROI = (150 / 1920, 200 / 1080, 1310 / 1920, 835 / 1080)

# Область легенды «Крепость» внизу экрана (для детектора статистики).
FORTRESS_ROI = (220 / 1920, 840 / 1080, 420 / 1920, 900 / 1080)

# Область поиска декоративного маркера «Счёт» (шапка, правая часть).
SCORE_MARKER_ROI = (1250 / 1920, 0 / 1080, 1800 / 1920, 220 / 1080)

# Координаты клика по слотам в столбце «Рейтинг» (для подсветки).
#
# На реальном экране «Счёт» пользователь проверил, что y=477 попадает
# в верхнюю часть 4-го слота, а не во 2-й. Поэтому возвращаем проверенную
# раскладку строк из старой версии: slot 1 примерно 291, затем шаг около
# 67 px. Слот 1 выбран автоматически и не кликается.
#
# Координаты хранятся как доли viewport; _click_slot() добавляет left/top
# клиентской области окна.
RATING_SLOT_FRAC = {
    # slot: (fx, fy) — доля окна. Слот 1 пропускаем.
    2: (1626 / 1920, 359 / 1080),
    3: (1623 / 1920, 427 / 1080),
    4: (1622 / 1920, 495 / 1080),
    5: (1619 / 1920, 562 / 1080),
    6: (1628 / 1920, 630 / 1080),
    7: (1626 / 1920, 698 / 1080),
    8: (1627 / 1920, 766 / 1080),
}

# ---------------------------------------------------------------------------
# Защита от преждевременного клика «Пропустить» (проблема 3)
# ---------------------------------------------------------------------------

# Маркер экрана «Статистика» (_tools/Маркер статистики.jpg): если после клика
# «Пропустить» пользователь успел нажать его раньше нас, анимация закончилась
# и НАШ клик в ту же точку попал по «Далее» — мы оказываемся на «Статистике».
# Маркер уникален: NCC ~0.999 на «Статистике», <=0.73 на графике/лобби.
STATS_MARKER_PATH = str(Path(__file__).resolve().parent.parent
                        / "_tools" / "Маркер статистики.jpg")

# Зона поиска маркера «Статистика» (доли окна). Маркер снят в ~(0.080, 0.194).
STATS_MARKER_ROI = (0.0, 0.10, 0.18, 0.30)

# Порог NCC для маркера «Статистика».
STATS_MARKER_THRESHOLD = 0.85

# Кнопка «Назад» на экране «Статистика» — возврат на график (доли окна).
BACK_BUTTON_FRAC = (0.0883, 0.9556)


@dataclass(frozen=True)
class DetectorConfig:
    """Все настройки детектора с осмысленными значениями по умолчанию."""

    # --- Детекция экрана статистики -------------------------------------
    required_screen_templates: tuple = ("fortress", "score_marker")

    # Пороги TM_CCOEFF_NORMED для шаблонов-детекторов экрана.
    # fortress — единственный НАДЁЖНЫЙ отличитель статистики от лобби,
    # поэтому его порог держим высоким (0.85): на статистике 1.0, на лобби 0.57.
    screen_template_thresholds: Dict[str, float] = field(
        default_factory=lambda: {"fortress": 0.85, "score_marker": 0.50})

    # Сколько ПОСЛЕДОВАТЕЛЬНЫХ кадров должны подтвердить экран статистики.
    # 1 кадра достаточно: fortress_icon даёт NCC ~1.0 на статистике и ~0.57
    # на лобби (порог 0.85), поэтому ложных срабатываний нет. Меньшее значение
    # = быстрее блокируется ввод пользователя (раньше жмём «Пропустить» сами).
    confirm_streak: int = 1

    # Период опроса экрана монитором, сек. 0.25 — ввод пользователя
    # блокируется уже через ~0.3с после появления статистики (вместо 1–1.5с).
    monitor_poll: float = 0.25

    # Максимальное время ожидания экрана статистики (None = без лимита).
    monitor_timeout: Optional[float] = None

    # Максимальное время анализа после обнаружения экрана, сек.
    analysis_timeout: float = 30.0

    # Сколько попыток анализа сделать, если иконки не найдены с первого раза.
    analysis_attempts: Optional[int] = None

    # Пауза между попытками анализа, сек.
    analysis_retry_delay: float = 0.4

    # --- Вкладка «Счёт» ------------------------------------------------
    # Экран статистики открывается на «Войсках»: полный набор иконок бывает
    # только на «Счёте» — кликаем по вкладке сразу после подтверждения экрана.
    click_score_tab: bool = True

    score_tab_roi: Tuple[float, float, float, float] = SCORE_TAB_ROI

    # Пауза после клика по вкладке (отрисовка графика), сек. Двойной клик.
    tab_settle: float = 0.6

    # --- Защита от преждевременного клика «Пропустить» (проблема 3) -------
    # Если пользователь успел нажать «Пропустить» до блокировки ввода,
    # анимация заканчивается, и НАШ клик в ту же точку попадает по «Далее» ->
    # мы на экране «Статистика». Сторожевой цикл анализа ловит это по маркеру
    # «Статистики» и возвращается на график кнопкой «Назад».

    # Путь к маркеру «Статистика» (_tools/Маркер статистики.jpg).
    stats_marker_path: str = STATS_MARKER_PATH

    # Зона поиска маркера «Статистика» (доли окна x0,y0,x1,y1).
    stats_marker_roi: Tuple[float, float, float, float] = STATS_MARKER_ROI

    # Порог NCC для маркера «Статистика».
    stats_marker_threshold: float = STATS_MARKER_THRESHOLD

    # Кнопка «Назад» на экране «Статистика» (доли окна).
    back_button_frac: Tuple[float, float] = BACK_BUTTON_FRAC

    # Жмём ли «Пропустить», чтобы проскочить постепенное появление вкладок.
    click_skip: bool = True

    # Кнопка «Пропустить».
    skip_button_frac: Tuple[float, float] = SKIP_BUTTON_FRAC

    # --- Клик по слотам для подсветки цвета ----------------------------
    # Кликнуть по каждому слоту в «Рейтинге», чтобы его цвет стал ярче
    # (по нему проще определить цвет линии). Выключаем, если не нужно.
    click_slots: bool = True

    # Доли окна для кликов по слотам 2..8 (слот 1 — по умолчанию).
    # Координаты намеренно хранятся как доли viewport, а не как абсолютные px.
    rating_slot_frac: Dict[int, Tuple[float, float]] = field(
        default_factory=lambda: dict(RATING_SLOT_FRAC))

    # Пауза после клика по слоту, сек.
    slot_settle: float = 0.4

    # --- Зоны UI --------------------------------------------------------
    chart_roi: Tuple[float, float, float, float] = CHART_ROI
    icon_fallback_roi: Tuple[float, float, float, float] = ICON_FALLBACK_ROI
    fortress_roi: Tuple[float, float, float, float] = FORTRESS_ROI
    score_marker_roi: Tuple[float, float, float, float] = SCORE_MARKER_ROI

    # Если в chart_roi иконки не найдены — искать в icon_fallback_roi.
    full_screen_icon_fallback: bool = True

    # --- Поиск иконок победы/поражения ----------------------------------
    icon_threshold: float = 0.72

    # Минимальная дистанция между центрами иконок (NMS), px @1080p.
    icon_nms_distance: float = 18.0

    # --- Определение цвета линии под иконкой ----------------------------
    # Допуск по евклидову расстоянию в RGB между пикселем линии и цветом
    # игрока (учитывает антиалиасинг и приглушённую нитку).
    color_tolerance: float = 45.0

    # Минимальная длина непрерывного «забега» столбцов с цветом игрока.
    color_min_run: int = 3

    # Минимальное общее число пикселей цвета игрока в зоне замера.
    color_min_pixels: int = 6

    # Зона замера у иконки (см. color_analyzer):
    line_scan: Dict[str, float] = field(
        default_factory=lambda: {
            "gap": 40.0, "trace_len": 260.0, "dy": 45.0, "min_pts": 8.0,
            "max_dy": 14.0, "pass_dy": 25.0, "tie_dy": 5.0,
            "slope_min": 0.008, "dx_offset": 0.70})

    # Если слева от иконки цвет не найден — пробовать справа.
    scan_right_fallback: bool = True

    # --- Результат и отладка --------------------------------------------
    debug: bool = False

    # Папка для отладочных кадров.
    debug_dir: str = str(Path(__file__).resolve().parent.parent
                         / "config" / "match_debug")

    # Кнопка «ДАЛЕЕ» после анализа (опционально).
    next_button_roi: Tuple[float, float, float, float] = (
        1650 / 1920, 1010 / 1080, 1850 / 1920, 1060 / 1080)

    # Ближайший цвет игрока дальше этого расстояния (RGB) считается
    # «не распознанным».
    max_player_color_distance: float = 80.0

    @classmethod
    def from_dict(cls, data: Optional[Dict[str, Any]] = None) -> "DetectorConfig":
        """Создать конфиг из словаря-переопределений (вложенные dict сливаются)."""
        cfg = cls()
        if not data:
            return cfg
        valid = {f.name for f in fields(cls)}
        updates = {}
        for k, v in data.items():
            if k not in valid:
                continue
            cur = getattr(cfg, k)
            if isinstance(cur, dict) and isinstance(v, dict):
                merged = dict(cur)
                merged.update(v)
                updates[k] = merged
            else:
                updates[k] = v
        return replace(cfg, **updates)

    # --- Хелперы ---------------------------------------------------------
    def scale_for(self, width: int, height: int) -> float:
        """Коэффициент масштаба шаблонов под текущий кадр."""
        ref_w, ref_h = REFERENCE_RESOLUTION
        if not width or not height:
            return 1.0
        return min(width / ref_w, height / ref_h)

    def roi_pixels(self, roi, width: int, height: int):
        """Доли -> целочисленный прямоугольник (x0, y0, x1, y1) в пикселях."""
        if roi is None:
            return (0, 0, width, height)
        fx0, fy0, fx1, fy1 = roi
        x0 = max(0, min(width - 1, int(fx0 * width)))
        y0 = max(0, min(height - 1, int(fy0 * height)))
        x1 = max(x0 + 1, min(width, int(fx1 * width)))
        y1 = max(y0 + 1, min(height, int(fy1 * height)))
        return (x0, y0, x1, y1)