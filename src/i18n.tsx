function replaceLocalized(source:string,replacements:Array<[string,string]>) {
  let result=source
  for(const[from,to]of replacements){
    if(!result.includes(from))continue
    if(/^[\p{L}-]+$/u.test(from)){
      const escaped=from.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')
      result=result.replace(new RegExp(`(^|[^\\p{L}])${escaped}(?=$|[^\\p{L}])`,'gu'),(_match,prefix:string)=>`${prefix}${to}`)
    }else result=result.split(from).join(to)
  }
  return result
}

export function translateText(source:string,language:AppLanguage=currentLanguage){
  const leading=source.match(/^\s*/)?.[0]??'';const trailing=source.match(/\s*$/)?.[0]??'';const trimmed=source.trim()
  const exact=language==='en'?BASE_TRANSLATIONS[trimmed]:dynamicByLanguage[language]?.[trimmed]??STATIC_RU[trimmed]
  if(exact!==undefined)return`${leading}${exact}${trailing}`
  return replaceLocalized(source,replacementsByLanguage[language]??[])
}

interface I18nContextValue {
  language: AppLanguage
  setLanguage: (language: AppLanguage) => void
  t: (source: string) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

type LocalizedDomState={language:AppLanguage;revision:number;original:string;translated:string}
const localizedTextState=new WeakMap<Node,LocalizedDomState>()
const localizedAttributeState=new WeakMap<Element,Map<string,LocalizedDomState>>()

function translateDomNode(node: Node,language:AppLanguage) {
  if (node.nodeType === Node.TEXT_NODE) {
    const parent = node.parentElement
    if (!parent || parent.closest('.language-selection-screen') || ['SCRIPT', 'STYLE', 'CODE', 'PRE', 'TEXTAREA'].includes(parent.tagName)) return
    const current=node.nodeValue??''
    const previous=localizedTextState.get(node)
    if(previous&&previous.language===language&&previous.revision===translationRevision&&current===previous.translated)return
    const original=previous&&current===previous.translated?previous.original:current
    const translated=translateText(original,language)
    localizedTextState.set(node,{language,revision:translationRevision,original,translated})
    if(translated!==current)node.nodeValue=translated
    return
  }
  if (!(node instanceof Element)) return
  if (node.closest('.language-selection-screen') || ['SCRIPT', 'STYLE', 'CODE', 'PRE', 'TEXTAREA'].includes(node.tagName)) return
  const attributeStates=localizedAttributeState.get(node)??new Map<string,LocalizedDomState>()
  localizedAttributeState.set(node,attributeStates)
  for (const attribute of ['title', 'placeholder', 'aria-label', 'alt']) {
    const current=node.getAttribute(attribute)
    if (!current) continue
    const previous=attributeStates.get(attribute)
    if(previous&&previous.language===language&&previous.revision===translationRevision&&current===previous.translated)continue
    const original=previous&&current===previous.translated?previous.original:current
    const translated=translateText(original,language)
    attributeStates.set(attribute,{language,revision:translationRevision,original,translated})
    if(translated!==current)node.setAttribute(attribute,translated)
  }
  for (const child of [...node.childNodes]) translateDomNode(child,language)
}

function DocumentLocalizer({ language }: { language: AppLanguage }) {
  useEffect(() => {
    currentLanguage = language
    document.documentElement.lang = language
    document.title = language === 'en' ? 'War of the Ring — Map Editor' : 'Война за Кольцо — редактор карты'

    const refresh=()=>translateDomNode(document.body,language)
    refresh()
    window.addEventListener('wotr-translations-changed',refresh)
    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === 'characterData') translateDomNode(mutation.target,language)
        else if (mutation.type === 'attributes') translateDomNode(mutation.target,language)
        else for (const node of [...mutation.addedNodes]) translateDomNode(node,language)
      }
    })
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['title', 'placeholder', 'aria-label', 'alt'],
    })

    const originalConfirm = window.confirm.bind(window)
    const originalAlert = window.alert.bind(window)
    window.confirm = (message?: string) => originalConfirm(translateText(String(message ?? ''), language))
    window.alert = (message?: unknown) => originalAlert(translateText(String(message ?? ''), language))
    return () => {
      observer.disconnect()
      window.removeEventListener('wotr-translations-changed',refresh)
      window.confirm = originalConfirm
      window.alert = originalAlert
    }
  }, [language])
  return null
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>('en')
  const setLanguage = useCallback((next: AppLanguage) => {
    currentLanguage = next
    setLanguageState(next)
  }, [])
  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (source) => translateText(source, language),
  }), [language, setLanguage])
  return <I18nContext.Provider value={value}><DocumentLocalizer language={language} />{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used inside I18nProvider')
  return context
}
